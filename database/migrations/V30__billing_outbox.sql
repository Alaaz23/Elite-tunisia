-- V30 : outbox de facturation après retour (Lot A.3, complété en Lot A.4).
-- Le retour écrit une ligne PENDING dans la même transaction que la transition COMPLETED :
-- atomicité retour / demande de facturation. Un worker génère ensuite la facture principale
-- dans sa propre transaction. Une génération en échec ne bloque pas le retour.
-- UNIQUE (booking_id, kind) : une seule demande de facture principale par réservation.
-- Reprise : next_attempt_at suit le backoff (1 min, 5 min, 15 min, 1 h) ; 5 échecs → DEAD.
-- cycle_attempts est remis à zéro par une reprise administrative ; attempts et billing_request_history ne le sont jamais.
CREATE TABLE billing_requests (
    id              uuid PRIMARY KEY,
    booking_id      uuid NOT NULL REFERENCES bookings(id),
    kind            varchar(40) NOT NULL CHECK (kind IN ('MAIN_INVOICE')),
    status          varchar(20) NOT NULL DEFAULT 'PENDING' CHECK (status IN ('PENDING', 'DONE', 'DEAD')),
    attempts        integer NOT NULL DEFAULT 0 CHECK (attempts >= 0),
    cycle_attempts  integer NOT NULL DEFAULT 0 CHECK (cycle_attempts >= 0),
    next_attempt_at timestamptz,
    last_attempt_at timestamptz,
    last_error      varchar(1000),
    invoice_id      uuid REFERENCES invoices(id),
    requested_by    uuid NOT NULL REFERENCES users(id),
    created_at      timestamptz NOT NULL,
    completed_at    timestamptz,
    CONSTRAINT uq_billing_requests_booking_kind UNIQUE (booking_id, kind),
    CONSTRAINT ck_billing_requests_done CHECK (status <> 'DONE' OR (invoice_id IS NOT NULL AND completed_at IS NOT NULL)),
    CONSTRAINT ck_billing_requests_pending_due CHECK (status <> 'PENDING' OR next_attempt_at IS NOT NULL)
);

CREATE INDEX ix_billing_requests_due ON billing_requests (next_attempt_at) WHERE status = 'PENDING';

CREATE TABLE billing_request_history (
    id           bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    request_id   uuid NOT NULL REFERENCES billing_requests(id),
    occurred_at  timestamptz NOT NULL,
    event        varchar(30) NOT NULL CHECK (event IN ('ENQUEUED', 'ATTEMPT_FAILED', 'DONE', 'DEAD', 'MANUAL_RETRY')),
    attempt_no   integer CHECK (attempt_no IS NULL OR attempt_no > 0),
    error        varchar(1000),
    actor_id     uuid REFERENCES users(id),
    reason       varchar(500),
    CONSTRAINT ck_billing_request_history_retry CHECK (event <> 'MANUAL_RETRY' OR (actor_id IS NOT NULL AND reason IS NOT NULL))
);

CREATE INDEX ix_billing_request_history_request ON billing_request_history (request_id, id);

-- Verrou de la rétrofacturation : une seule exécution à la fois (ligne unique, mise à jour conditionnelle).
CREATE TABLE billing_backfill_lock (
    id          smallint PRIMARY KEY CHECK (id = 1),
    run_id      uuid,
    actor_id    uuid REFERENCES users(id),
    started_at  timestamptz,
    CONSTRAINT ck_billing_backfill_lock_run CHECK ((run_id IS NULL) = (started_at IS NULL) AND (run_id IS NULL) = (actor_id IS NULL))
);

